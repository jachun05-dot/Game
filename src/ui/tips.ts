/** 지금 띄울 안내(본 것·꺼 둔 것은 빼고, 우선순위가 가장 높은 하나) */
export function currentTip(s: GameState, seen: string[], off: boolean): Tip | null {
  if (off) return null;
  return TIPS.find((t) => !seen.includes(t.id) && t.when(s)) ?? null;
}
